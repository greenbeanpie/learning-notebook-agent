/// `tr` with `{0}`, `{1}`… placeholders filled from `args`.
pub fn trf(en: bool, key: &str, args: &[&dyn std::fmt::Display]) -> String {
    let mut s = tr(en, key).to_string();
    for (i, a) in args.iter().enumerate() {
        s = s.replace(&format!("{{{i}}}"), &a.to_string());
    }
    s
}

