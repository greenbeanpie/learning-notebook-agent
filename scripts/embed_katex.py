#!/usr/bin/env python3
"""Embed KaTeX into the shared lecture/slide player page and sync its per-platform copies.

Source: apps/windows/LocalNotebook/Assets/katex (katex 0.16.11). The block between the markers
<!-- KATEX:BEGIN --> and <!-- KATEX:END --> in apps/shared/deck_player.html is regenerated:
katex.min.css (only the @font-face rules of the embedded fonts, as base64 woff2 data: URIs),
katex.min.js and the mhchem extension. Running the script again produces the same bytes.
Afterwards the page is copied (byte for byte) to the macOS and Linux client folders; the
crates/lna-api/tests/shared_assets.rs test requires the three copies to be identical.

Usage: python3 scripts/embed_katex.py
"""
import base64
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
KATEX = ROOT / "apps/windows/LocalNotebook/Assets/katex"
SHARED = ROOT / "apps/shared/deck_player.html"
COPIES = [
    ROOT / "apps/macos/LocalNotebook/Sources/LocalNotebook/Resources/deck_player.html",
    ROOT / "apps/linux/local-notebook-gtk/assets/deck_player.html",
]
BEGIN = "<!-- KATEX:BEGIN -->"
END = "<!-- KATEX:END -->"

FONTS = [
    "KaTeX_Main-Regular",
    "KaTeX_Main-Bold",
    "KaTeX_Main-Italic",
    "KaTeX_Main-BoldItalic",
    "KaTeX_Math-Italic",
    "KaTeX_Math-BoldItalic",
    "KaTeX_AMS-Regular",
    "KaTeX_Caligraphic-Regular",
    "KaTeX_Size1-Regular",
    "KaTeX_Size2-Regular",
    "KaTeX_Size3-Regular",
    "KaTeX_Size4-Regular",
]

LICENSE_NOTE = (
    "<!-- KaTeX 0.16.11 (https://katex.org) is MIT licensed. Copyright (c) 2013-2020 Khan Academy and\n"
    "     other contributors. Permission is granted, free of charge, to use, copy, modify, merge, publish,\n"
    "     distribute, sublicense and/or sell copies of the software, provided this notice and the MIT\n"
    "     permission notice (see apps/windows/LocalNotebook/Assets/katex/LICENSE.txt) are included. The\n"
    "     software is provided \"as is\", without warranty of any kind. Generated by scripts/embed_katex.py;\n"
    "     do not edit by hand. -->\n"
)


def read(p: Path) -> str:
    return p.read_text(encoding="utf-8")


def build_css() -> str:
    css = read(KATEX / "katex.min.css")
    faces = re.findall(r"@font-face\{[^}]*\}", css)
    rest = re.sub(r"@font-face\{[^}]*\}", "", css)
    kept = []
    for face in faces:
        m = re.search(r"url\(fonts/([A-Za-z0-9_-]+)\.woff2\)", face)
        if not m or m.group(1) not in FONTS:
            continue
        name = m.group(1)
        head = face.split("src:", 1)[0]
        data = base64.b64encode((KATEX / "fonts" / f"{name}.woff2").read_bytes()).decode("ascii")
        kept.append(f'{head}src:url(data:font/woff2;base64,{data}) format("woff2")}}')
    if len(kept) != len(FONTS):
        sys.exit(f"expected {len(FONTS)} @font-face rules, found {len(kept)}")
    out = "".join(kept) + rest
    if "url(fonts/" in out or re.search(r"url\((?!data:)", out):
        sys.exit("a non-embedded url() reference is left in the KaTeX CSS")
    return out


def script_text(name: str) -> str:
    js = read(KATEX / name)
    # a literal "</script" would end the inline script element
    return re.sub(r"</(script)", r"<\\/\1", js, flags=re.IGNORECASE)


def build_block() -> str:
    block = (
        f"{BEGIN}\n{LICENSE_NOTE}"
        f"<style>\n{build_css()}\n</style>\n"
        f"<script>\n{script_text('katex.min.js')}\n</script>\n"
        f"<script>\n{script_text('mhchem.min.js')}\n</script>\n"
        f"{END}"
    )
    # the hosts replace template tokens everywhere in the page; none may occur in the block
    bad = re.search(r"__[A-Z][A-Z_]*__", block)
    if bad:
        sys.exit(f"template-like token {bad.group(0)} in the KaTeX block")
    return block


def main() -> None:
    page = read(SHARED)
    block = build_block()
    if BEGIN in page and END in page:
        a = page.index(BEGIN)
        b = page.index(END) + len(END)
        page = page[:a] + block + page[b:]
    elif "</head>" in page:
        page = page.replace("</head>", block + "\n</head>", 1)
    else:
        sys.exit("no </head> in the shared page")
    SHARED.write_bytes(page.encode("utf-8"))
    for dst in COPIES:
        dst.write_bytes(page.encode("utf-8"))
    print(f"embedded KaTeX block ({len(block) // 1024} KiB); page is {len(page.encode('utf-8')) // 1024} KiB; copies synced")


if __name__ == "__main__":
    main()
